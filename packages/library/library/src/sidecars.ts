/**
 * Sidecar files the librarian maintains inside each notebook directory:
 * `index.json`, the ingest-time structure/search index, and `ask-log.json`,
 * the durable ask history. Both are plain JSON validated at the read boundary
 * with zod; a file that is missing or fails validation is rebuilt (index) or
 * treated as empty (ask log) rather than failing the caller, because both are
 * derived or append-only data the service can recover from.
 * @module @deepseek-ai/dsh-library/src/sidecars
 */

import { z } from 'zod'
import { ASK_ORIGINS, RESOURCE_KINDS, RESOURCE_STATUSES } from './types.ts'
import type { ResourceId } from './types.ts'

/** File name of the ingest-time index inside one notebook directory. */
export const INDEX_FILE = 'index.json'

/** File name of the ask history inside one notebook directory. */
export const ASK_LOG_FILE = 'ask-log.json'

/** Newest entries kept in one ask log; older entries fall off the front. */
export const ASK_LOG_LIMIT = 200

/** Characters of leading converted text kept as a resource summary. */
export const SUMMARY_CHARS = 280

const resourceId = z.string().min(1).transform(value => value as ResourceId)

/** One pre-chunked, pre-tokenized retrieval unit inside the index. */
export const indexedChunk = z.object({
  heading: z.string(),
  text: z.string(),
  terms: z.record(z.string(), z.number()),
})

/** One indexed resource: identity, navigation outline, summary, and chunks. */
export const indexedResource = z.object({
  resourceId,
  name: z.string().min(1),
  kind: z.enum(RESOURCE_KINDS),
  status: z.enum(RESOURCE_STATUSES),
  outline: z.array(z.string()),
  summary: z.string(),
  chunks: z.array(indexedChunk),
})

/**
 * The whole `index.json` payload: the structure listing plus the search
 * corpus of one notebook, regenerated by the librarian on every content
 * mutation so structure reads and searches never re-read the documents.
 */
export const notebookIndex = z.object({
  version: z.literal(1),
  title: z.string(),
  updatedAt: z.string().min(1),
  resources: z.array(indexedResource),
})

/** One parsed `index.json`, inferred from {@link notebookIndex}. */
export type NotebookIndex = z.infer<typeof notebookIndex>

/** One indexed resource entry, inferred from {@link indexedResource}. */
export type IndexedResource = z.infer<typeof indexedResource>

const askSource = z.object({
  resourceId,
  name: z.string(),
  heading: z.string(),
})

/** One recorded ask exchange at the durable boundary. */
export const askLogEntry = z.object({
  id: z.string().min(1),
  origin: z.enum(ASK_ORIGINS),
  question: z.string(),
  answer: z.string(),
  grounded: z.boolean(),
  sources: z.array(askSource),
  createdAt: z.string().min(1),
})

/** The whole `ask-log.json` payload: exchanges in chronological order. */
export const askLog = z.object({
  version: z.literal(1),
  entries: z.array(askLogEntry),
})

/** One parsed `ask-log.json`, inferred from {@link askLog}. */
export type AskLog = z.infer<typeof askLog>
